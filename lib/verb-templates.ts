/* 检查动词释义是否属于状态动词 */
export function isStativeVerb(meaning: string): boolean {
  for (const fieldName of STATIVE_FIELDS) {
    const mf = VERB_MICRO_FIELDS.find(m => m.field === fieldName);
    if (mf && mf.keywords.some(kw => meaning.includes(kw))) return true;
  }
  return false;
}

/**
 * 语义兼容性校验（白名单 + 黑名单双重机制）
 *
 * 检查顺序（短路求值）：
 *   1. 不兼容上下文检查（黑名单）：如果句子包含该微场的不兼容词，立即拒绝
 *      → 堵住"学会断言细节"这类漏洞（通用学习词 + 不兼容宾语）
 *   2. 兼容上下文检查（白名单）：句子必须包含至少一个兼容词或通用学习词
 *      → 拒绝"迎合难点"这类不兼容句子（无兼容词）
 *
 * @param cn 已填入释义的中文句子（{M}已替换为释义）
 * @param meaning 动词中文释义
 * @returns true if compatible, false if incompatible
 */
export function validateVerbSentence(cn: string, meaning: string): boolean {
  const mf = detectVerbField(meaning);

  if (!mf) {
    // 未匹配到微场 → 使用中性模板
    if (isStativeVerb(meaning)) {
      // 状态动词：检查是否包含观察类词汇
      return STATIVE_OBSERVATION_WORDS.some(w => cn.includes(w));
    }
    // 动作动词：检查是否包含通用学习词
    return UNIVERSAL_LEARNING_WORDS.some(w => cn.includes(w));
  }

  // ★ 第1道：不兼容上下文检查（黑名单优先）
  // 即使句子包含通用学习词，只要出现不兼容宾语就拒绝
  const incompatible = FIELD_INCOMPATIBLE_CTX[mf.field] || [];
  if (incompatible.some(w => cn.includes(w))) {
    return false;
  }

  // ★ 第2道：兼容上下文检查（白名单）
  const compatible = FIELD_COMPATIBLE_CTX[mf.field] || [];
  const hasCompatible = compatible.some(w => cn.includes(w));
  const hasUniversal = UNIVERSAL_LEARNING_WORDS.some(w => cn.includes(w));

  return hasCompatible || hasUniversal;
}

/**
 * 获取通用兜底句子（当所有模板都校验失败时使用）
 *
 * 对于动作动词：使用"学会X"句式（任何动作动词都能"学会"）
 * 对于状态动词：使用"关于X"句式（任何状态都能"观察"）
 */
export function getUniversalFallback(meaning: string, person: string): string {
  if (isStativeVerb(meaning)) {
    return `关于${meaning}，${person}有自己独到的观察`;
  }
  return `学会${meaning}并不容易，但${person}从未放弃`;
}
