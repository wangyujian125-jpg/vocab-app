/* ============================================================
 *  动词微场检测函数
 *  按顺序匹配，返回第一个匹配的微场
 * ============================================================ */
export function detectVerbField(meaning: string): VerbMicroField | null {
  for (const mf of VERB_MICRO_FIELDS) {
    for (const kw of mf.keywords) {
      if (meaning.indexOf(kw) >= 0) return mf;
    }
  }
  return null;
}

/* ============================================================
 *  获取动词模板（微场优先，中性兜底）
 * ============================================================ */
export function getVerbTemplates(meaning: string): string[] {
  const mf = detectVerbField(meaning);
  if (mf) return mf.templates;
  if (isStativeVerb(meaning)) return STATIVE_NEUTRAL_TPL;
  return NEUTRAL_VERB_TPL;
}

