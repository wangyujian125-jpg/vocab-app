/* ============================================================
 *  动词精细微场模板库  verb-templates.ts
 *
 *  核心原理：
 *    每个微场内的动词共享相同的论元结构（argument structure）
 *    和语义角色（semantic role），因此可以安全地共享同一组模板。
 *    匹配不到任何微场的动词使用"绝对中性模板"兜底。
 *
 *  设计原则：
 *    1. {M} = 动词中文释义，必须出现在该动词语法正确的位置
 *    2. 模板上下文必须与该微场所有动词的语义兼容
 *    3. 上下文提供足够线索让用户推断词义，但不直接暴露释义
 *    4. {P} = 人名占位符
 *
 *  与旧系统的区别：
 *    旧系统只有8个大语义场，把"适应"和"迎合"混在一起，
 *    导致"她花了整整一个月去迎合"这种语义错误。
 *    新系统将它们分离到不同微场，各自拥有语义兼容的模板。
 * ============================================================ */

